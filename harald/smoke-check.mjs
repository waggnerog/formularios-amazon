import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Script } from 'node:vm';
const html=readFileSync('harald/index.html','utf8');
const cloud=readFileSync('harald/cloud.js','utf8');
const people=readFileSync('harald/people.js','utf8');
const peopleStyles=readFileSync('harald/people.css','utf8');
new Script(cloud,{filename:'harald/cloud.js'});
new Script(people,{filename:'harald/people.js'});
const dataTag=html.match(/<script id="sistematica-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(dataTag,'Bloco de metadados nao encontrado');
const data=JSON.parse(dataTag[1]);
assert.deepEqual(data.stores,[],'Lojas nao podem estar embutidas no HTML publico');
assert.deepEqual(data.teams,[],'Setores nao podem estar embutidos no HTML publico');
assert.ok(html.includes('href="./cloud.css"'),'Estilo de login nao carregado');
assert.ok(html.includes('src="./cloud.js"'),'Cliente Supabase nao carregado');
assert.ok(html.includes('src="./people.js"'),'Central de pessoas nao carregada');
assert.ok(html.includes('href="./lists.css"'),'CSS da lista de setores ausente');
assert.ok(html.includes('class="sectorListRow'),'Setores nao sao exibidos como linhas');
assert.ok(html.includes('data-filter="contact"'),'Filtro de contato ausente');
assert.ok(people.includes('hpSectorRows'),'Equipe e historico precisa seguir o padrao de lista');
assert.ok(people.includes('hpSectorDrawer'),'Drawer lateral do setor ausente');
assert.ok(people.includes('id="hpContactFilter"'),'Filtro de contato da central ausente');
assert.ok(html.includes('href="./people.css"'),'CSS da central de pessoas ausente');
assert.ok(peopleStyles.includes('.hpOverlay'),'Interface principal sem estilos');
assert.ok(cloud.includes('harald_horista_console_rows'),'Fonte operacional Horista nao consultada');
assert.ok(people.includes('sourceManaged'),'Central precisa respeitar a fonte externa somente leitura');
assert.ok(cloud.includes('role==="admin"?getAll("harald_horista_private_rows"'),'Acesso restrito aos dados pessoais Horistas nao aplicado');
assert.ok(!people.includes('service_role'),'Chave privilegiada proibida');
assert.ok(html.includes('window.haraldCloud.start()'),'Boot seguro ausente');
assert.ok(html.includes('HORISTAS · C2'),'Escopo fixo Horista ausente');
assert.ok(html.includes('Controle Operacional Horistas.xlsx'),'Fonte oficial nao identificada no painel');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].filter(m=>!m[0].includes('type="application/json"')&&!m[0].includes('src='));
assert.equal(scripts.length,1,'Esperado exatamente um script do painel');
new Script(scripts[0][1],{filename:'harald/index.html:inline.js'});
assert.ok(!html.includes('GH1-RS-009|4|92016757006718'),'Base historica detectada no HTML');
assert.ok(cloud.includes('harald_members?select=role'),'Validacao de autorizacao ausente');
assert.ok(cloud.includes('sessionStorage'),'Sessao nao configurada');
assert.ok(!cloud.includes('service_role'),'Proibido expor chave privilegiada no navegador');
console.log('HARALD: sintaxe, autenticacao e separacao dos dados OK.');